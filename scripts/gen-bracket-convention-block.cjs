#!/usr/bin/env node
'use strict';

/**
 * gen-bracket-convention-block.cjs — single-sources the bracket phase-ID
 * convention block and stamps it into every prompt-surface file that TEACHES
 * phase naming (see MANIFEST below).
 *
 * Usage:
 *   node scripts/gen-bracket-convention-block.cjs           # same as --check
 *   node scripts/gen-bracket-convention-block.cjs --check   # exit 1 if any target's block is missing/stale
 *   node scripts/gen-bracket-convention-block.cjs --write    # stamp/refresh the block in every target
 *   node scripts/gen-bracket-convention-block.cjs --print    # print the canonical block to stdout
 *
 * #612 PR-6 (injection, local prototype). Upstream PR-6's approved design is a
 * single-sourced, GENERATED convention block injected into every phase-naming
 * surface with a verify parity check so the copies cannot drift. This is the
 * local prototype of that mechanism: ONE canonical BLOCK (the single source) is
 * stamped between the BEGIN/END markers into each MANIFEST target. `--check` is
 * the parity gate — it fails if any target's block differs from the canonical
 * text (or is missing), so a hand-edit to a copy is caught in CI.
 *
 * The block is convention-CONDITIONAL: it instructs the reader to switch forms
 * only when `.planning/config.json` → `phase_id_convention` is `"bracket"`, so
 * `sequential`/`milestone-prefixed` repos are unaffected. The canonical grammar
 * lives in gsd-core/references/phase-id-convention.md — the block distills it and
 * must not contradict it.
 */

const fs = require('node:fs');
const path = require('node:path');

const { ExitError, runMain } = require('./lib/cli-exit.cjs');

const ROOT = path.resolve(__dirname, '..');

// ─── Markers ────────────────────────────────────────────────────────────────
const BEGIN_MARKER = '<!-- BEGIN:gsd-bracket-convention -->';
const END_MARKER = '<!-- END:gsd-bracket-convention -->';

// ─── MANIFEST ───────────────────────────────────────────────────────────────
// The explicit, reviewable contract: every prompt-surface file that TEACHES how
// to name/format a phase identifier (heading, checklist, phase dir, or plan
// file) in free text — i.e. a bracket-convention repo would otherwise read the
// file and emit the wrong (sequential) form. Repo-relative paths. NO globs: the
// stamping set is a hand-curated list, not a pattern match.
//
// agents/gsd-roadmapper.md is DELIBERATELY EXCLUDED — it already documents the
// bracket convention inline in full (reland 8b35a63b), so the block would be
// redundant/conflicting there.
const MANIFEST = [
  'gsd-core/templates/roadmap.md',
  'gsd-core/templates/phase-prompt.md',
  'gsd-core/workflows/new-project.md',
  'gsd-core/workflows/edit-phase.md',
  'agents/gsd-planner.md',
];

// ─── Canonical block (THE single source) ─────────────────────────────────────
// CONCISE by design — every target pays this as prompt-surface tokens. Keep it
// faithful to gsd-core/references/phase-id-convention.md; do not add forms the
// canonical doc does not specify (e.g. a `## [CODE.MM] Name` milestone heading —
// milestones remain `vX.Y`-labelled under bracket per getMilestoneFromPhaseId).
const BLOCK = [
  BEGIN_MARKER,
  '<!-- GENERATED by scripts/gen-bracket-convention-block.cjs — edit the canonical block there, then run `node scripts/gen-bracket-convention-block.cjs --write`. -->',
  '**Phase-ID convention.** Read `.planning/config.json` → `phase_id_convention`. When it is `"bracket"`, the milestone `MM` lives inside the `[CODE.MM]` prefix (`CODE` = `project_code`, `MM` = two-digit milestone, `NN` = two-digit phase, `SS` = optional sub-phase) — emit these forms, never a bare `Phase NN`:',
  '',
  '- ROADMAP checklist: `- [ ] **[CODE.MM] NN: Name**`',
  '- Phase detail heading: `### [CODE.MM] NN: Name`',
  '- `Depends on` / display token: `[CODE.MM] NN[.SS]` (e.g. `[CK.02] 05`, `[CK.02] 05.03`)',
  '- Phase directory: `CODE.MM-NN[.SS]-slug` (e.g. `CK.02-05-dashboard`)',
  '- Plan file: `NN-PP-PLAN.md` — phase + plan index only; the `[CODE.MM]` milestone prefix belongs in the DIR name, NEVER in the plan filename.',
  '',
  'When `phase_id_convention` is absent, `"sequential"`, or `"milestone-prefixed"`, keep the pre-existing forms in this file unchanged. Full grammar: `references/phase-id-convention.md`.',
  END_MARKER,
].join('\n');

/**
 * Return the canonical block text (the single source of truth).
 * @returns {string}
 */
function buildBlock() {
  return BLOCK;
}

// ─── Stamping ─────────────────────────────────────────────────────────────────

/**
 * Escape a string for literal use in a RegExp.
 * @param {string} s
 * @returns {string}
 */
function escapeRegExp(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

const BLOCK_RE = new RegExp(escapeRegExp(BEGIN_MARKER) + '[\\s\\S]*?' + escapeRegExp(END_MARKER));

/**
 * Produce the canonical stamped form of `content`:
 *   - If a block already exists (between the markers), replace it IN PLACE with
 *     the canonical BLOCK (idempotent — re-stamping is a no-op).
 *   - Otherwise append it. When the file ends with a lone horizontal-rule footer
 *     (a `---` line as the last non-blank content), insert the block BEFORE that
 *     footer; else append at end-of-file. In all cases the result ends with a
 *     single trailing newline.
 *
 * @param {string} content  Current file content.
 * @returns {string}        Content with the canonical block stamped in.
 */
function stamp(content) {
  if (BLOCK_RE.test(content)) {
    // Function replacer so `$` sequences inside BLOCK are treated literally.
    return content.replace(BLOCK_RE, () => BLOCK);
  }

  // Trailing lone-HR footer (e.g. a final `---`): insert the block before it.
  const footerMatch = content.match(/\n(-{3,})[ \t]*\s*$/);
  if (footerMatch) {
    const head = content.slice(0, footerMatch.index);
    const footer = content.slice(footerMatch.index + 1).replace(/\s+$/, '');
    return head.replace(/\n+$/, '\n') + '\n' + BLOCK + '\n\n' + footer + '\n';
  }

  // Plain append at EOF.
  return content.replace(/\n+$/, '\n') + '\n' + BLOCK + '\n';
}

/**
 * Normalize CRLF → LF so the parity check is line-ending agnostic.
 * @param {string} content
 * @returns {string}
 */
function normalizeLineEndings(content) {
  return content.replace(/\r/g, '');
}

// ─── Modes ────────────────────────────────────────────────────────────────────

/**
 * For each manifest target, compare its committed content against the stamped
 * form. Returns an array of { file, reason } for every stale/missing target.
 *
 * @param {string} [repoRoot]  Override for testing.
 * @returns {{ file: string, reason: string }[]}
 */
function findStale(repoRoot) {
  const resolvedRoot = repoRoot !== undefined ? repoRoot : ROOT;
  const stale = [];
  for (const rel of MANIFEST) {
    const abs = path.join(resolvedRoot, rel);
    let content;
    try {
      content = fs.readFileSync(abs, 'utf8');
    } catch (err) {
      stale.push({ file: rel, reason: 'unreadable: ' + String(err.message) });
      continue;
    }
    if (!BLOCK_RE.test(content)) {
      stale.push({ file: rel, reason: 'block missing' });
      continue;
    }
    const want = stamp(content);
    if (normalizeLineEndings(content) !== normalizeLineEndings(want)) {
      stale.push({ file: rel, reason: 'block differs from canonical text' });
    }
  }
  return stale;
}

/**
 * Stamp the canonical block into every manifest target. Returns the list of
 * files actually changed.
 *
 * @param {string} [repoRoot]  Override for testing.
 * @returns {string[]}  Repo-relative paths that changed.
 */
function writeAll(repoRoot) {
  const resolvedRoot = repoRoot !== undefined ? repoRoot : ROOT;
  const changed = [];
  for (const rel of MANIFEST) {
    const abs = path.join(resolvedRoot, rel);
    const content = fs.readFileSync(abs, 'utf8');
    const next = stamp(content);
    if (next !== content) {
      fs.writeFileSync(abs, next, 'utf8');
      changed.push(rel);
    }
  }
  return changed;
}

// ─── Main ─────────────────────────────────────────────────────────────────────

function main() {
  const flag = process.argv[2] || '--check';

  if (flag === '--print') {
    process.stdout.write(BLOCK + '\n');
    return;
  }

  if (flag === '--write') {
    const changed = writeAll();
    if (changed.length === 0) {
      process.stdout.write('bracket-convention block: all targets already up to date.\n');
    } else {
      for (const f of changed) process.stdout.write('  stamped  ' + f + '\n');
      process.stdout.write('\nStamped ' + changed.length + ' file(s). Re-run size:baseline if agents/workflows changed:\n');
      process.stdout.write('  npm run size:baseline\n');
    }
    // Verify idempotency: --check must pass immediately after --write.
    const stale = findStale();
    if (stale.length > 0) {
      process.stderr.write('ERROR: --check failed after --write (non-idempotent stamp):\n');
      for (const s of stale) process.stderr.write('  ' + s.file + ': ' + s.reason + '\n');
      throw new ExitError(1);
    }
    return;
  }

  if (flag === '--check') {
    const stale = findStale();
    if (stale.length > 0) {
      process.stderr.write('bracket-convention block is stale in ' + stale.length + ' target(s):\n');
      for (const s of stale) process.stderr.write('  ' + s.file + ': ' + s.reason + '\n');
      process.stderr.write('\nRun:\n  node scripts/gen-bracket-convention-block.cjs --write\n');
      throw new ExitError(1);
    }
    process.stdout.write('bracket-convention block: all ' + MANIFEST.length + ' targets up to date.\n');
    return;
  }

  throw new ExitError(
    1,
    'Unknown flag: ' + flag + '\nUsage: node scripts/gen-bracket-convention-block.cjs [--check|--write|--print]',
  );
}

// ─── Exports (for tests) ──────────────────────────────────────────────────────

module.exports = {
  MANIFEST,
  BLOCK,
  BEGIN_MARKER,
  END_MARKER,
  BLOCK_RE,
  buildBlock,
  stamp,
  normalizeLineEndings,
  findStale,
  writeAll,
};

// ─── CLI entry point ──────────────────────────────────────────────────────────

if (require.main === module) {
  runMain(main);
}
